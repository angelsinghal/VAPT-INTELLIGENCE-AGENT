"""Deterministic Markdown report generation.

No LLM is involved — this is pure Python string formatting.
"""

from __future__ import annotations

from datetime import UTC, datetime

from app.models.vapt import VAPTResult

_SEVERITY_EMOJI: dict[str, str] = {
    "Critical": "🔴",
    "High": "🟠",
    "Medium": "🟡",
    "Low": "🟢",
    "Informational": "🔵",
}

_CONFIDENCE_LABEL: dict[str, str] = {
    "High": "🎯 High",
    "Medium": "⚖️ Medium",
    "Low": "📉 Low",
}


def generate_markdown(result: VAPTResult) -> str:
    """Convert a validated ``VAPTResult`` into a professional Markdown report."""
    sev_emoji = _SEVERITY_EMOJI.get(result.severity, "⚪")
    conf_label = _CONFIDENCE_LABEL.get(result.confidence, result.confidence)
    timestamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")

    url_line = (
        f"**URL / Endpoint**: `{result.url}`" if result.url else "**URL / Endpoint**: Not specified"
    )
    param_line = (
        f"**Affected Parameter**: `{result.parameter}`"
        if result.parameter
        else "**Affected Parameter**: Not specified"
    )
    cwe_display = (
        f"[{result.cwe}](https://cwe.mitre.org/data/definitions/{result.cwe.replace('CWE-', '')}.html)"
        if result.cwe
        else "Not determined"
    )

    return f"""# VAPT Finding Report

**Generated**: {timestamp}

---

## {sev_emoji} {result.vulnerability_name}

| Field | Value |
|-------|-------|
| **Severity** | {sev_emoji} {result.severity} |
| **OWASP** | {result.owasp} |
| **CWE** | {cwe_display} |
| **Confidence** | {conf_label} |

---

## Affected Asset

{url_line}
{param_line}

---

## Description

{result.description}

---

## Impact

{result.impact}

---

## Proof of Concept

{result.poc}

---

## Remediation Plan

### 🚧 Immediate Mitigation (Ops/Infra)
{result.remediation.immediate_mitigation}

### 🛠️ Developer Root Cause Fix
{result.remediation.root_cause_fix}

### 📚 Official References
{chr(10).join(f"- {ref}" for ref in result.remediation.official_references)}

---

## Assessment Notes

{result.reasoning_summary}

> **Note**: Severity is an AI-assisted / evidence-based assessment and is NOT a replacement
> for a formal CVSS assessment.

---

*Report generated by VAPT Intelligence Agent.*
""".strip()


def generate_consolidated_report(results: list[VAPTResult]) -> str:
    """Generate a consolidated Markdown report for multiple findings."""
    if not results:
        return "# VAPT Consolidated Report\n\nNo findings to report."

    timestamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")

    severity_order = ["Critical", "High", "Medium", "Low", "Informational"]
    sorted_results = sorted(
        results,
        key=lambda r: severity_order.index(r.severity) if r.severity in severity_order else 99,
    )

    header = f"""# VAPT Consolidated Report

**Generated**: {timestamp}
**Total Findings**: {len(results)}

---

## Executive Summary

| Severity | Count |
|----------|-------|
"""
    counts: dict[str, int] = {}
    for r in results:
        counts[r.severity] = counts.get(r.severity, 0) + 1
    for sev in severity_order:
        if sev in counts:
            emoji = _SEVERITY_EMOJI.get(sev, "⚪")
            header += f"| {emoji} {sev} | {counts[sev]} |\n"

    header += "\n---\n\n## Findings\n\n"

    sections: list[str] = []
    for i, result in enumerate(sorted_results, 1):
        sev_emoji = _SEVERITY_EMOJI.get(result.severity, "⚪")
        sections.append(
            f"### {i}. {sev_emoji} {result.vulnerability_name}\n\n"
            f"- **Severity**: {result.severity}\n"
            f"- **OWASP**: {result.owasp}\n"
            f"- **CWE**: {result.cwe or 'Not determined'}\n"
            f"- **Confidence**: {result.confidence}\n"
            f"- **URL**: {result.url or 'Not specified'}\n"
            f"- **Parameter**: {result.parameter or 'Not specified'}\n\n"
            f"**Description**: {result.description}\n\n"
            f"**Impact**: {result.impact}\n\n"
            f"**Remediation**:\n"
            f"- *Mitigation*: {result.remediation.immediate_mitigation}\n"
            f"- *Root Cause Fix*: {result.remediation.root_cause_fix}\n"
            f"- *References*: {', '.join(result.remediation.official_references)}\n"
        )

    footer = (
        "\n---\n\n"
        "> **Note**: Severity ratings are AI-assisted / evidence-based assessments "
        "and are NOT replacements for formal CVSS assessments.\n\n"
        "*Report generated by VAPT Intelligence Agent.*"
    )

    return header + "\n---\n\n".join(sections) + footer
